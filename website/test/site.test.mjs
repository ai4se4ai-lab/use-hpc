import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile, stat } from 'node:fs/promises';
import { agents, installCommand } from '../app.js';

test('each target produces a scoped install of the shared skill', () => {
  for (const agent of ['codex', 'claude-code', 'opencode', 'cursor', 'github-copilot']) {
    const global = installCommand(agent);
    const project = installCommand(agent, 'project');
    assert.ok(global.includes(`--agent ${agent} --global`));
    assert.ok(!project.includes('--global'));
    for (const command of [global, project]) {
      assert.ok(command.includes('--skill use-hpc'));
      assert.ok(command.endsWith('--copy --yes'));
    }
  }
  assert.throws(() => installCommand('unknown'));
  assert.throws(() => installCommand('codex', 'unknown'));
});

test('all local navigation anchors and assets resolve', async () => {
  const html = await readFile(new URL('../index.html', import.meta.url), 'utf8');
  const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(match => match[1]);
  assert.equal(new Set(ids).size, ids.length, 'duplicate IDs');
  for (const [, anchor] of html.matchAll(/href="#([^"]+)"/g)) assert.ok(ids.includes(anchor), `missing #${anchor}`);
  for (const [, path] of html.matchAll(/(?:href|src)="\.\/([^"]+)"/g)) {
    if (path === 'changelog.html') continue; // Generated by the build; checked by check-build.mjs.
    assert.ok((await stat(new URL(`../${path}`, import.meta.url))).isFile());
  }
  for (const agent of Object.keys(agents)) assert.ok(html.includes(`data-agent="${agent}"`));
});

test('portable skill ships every resource linked from its entrypoint', async () => {
  const skill = new URL('../../plugins/use-hpc/skills/use-hpc/', import.meta.url);
  const markdown = await readFile(new URL('SKILL.md', skill), 'utf8');
  for (const [, path] of markdown.matchAll(/`((?:references|scripts)\/[\w./-]+)`/g)) {
    assert.ok((await stat(new URL(path, skill))).isFile());
  }
  for (const path of ['templates/hpc/config/experiments.json', 'templates/hpc/slurm/submit.py', 'scripts/scaffold.sh']) {
    assert.ok((await stat(new URL(path, skill))).isFile());
  }
});
